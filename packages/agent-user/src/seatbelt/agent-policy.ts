import { SbplProfileBuilder } from './profile-builder.ts';
import {
  allowProcesses,
  allowReads,
  allowWrites,
  DEFAULT_DENIED_LOCAL_PORTS,
  denyAllWrites,
  denyHomes,
  denyKeychains,
  denyLocalPorts,
  denyMounting,
  denyOtherVolumes,
  denyRawDevices,
} from './rules/index.ts';
import type { SandboxPolicy } from './sandbox-policy.ts';

export interface AgentPolicyInput {
  /** The agent user's home: readable and writable. */
  home: string;
  /** Card folders: readable and writable, wherever they are (also on another disk). */
  writableRoots: readonly string[];
  /** Extra read-only folders (shared tools). */
  readableRoots?: readonly string[];
  /** Local TCP ports the agent must not connect to. */
  deniedLocalPorts?: readonly number[];
}

/**
 * The Seatbelt profile agent commands run under, the second layer after the separate user. Adapted
 * from SandVault's profile: card folders on another disk are allowed instead of denying all of
 * /Volumes; the folders above them and /Users can be resolved, not listed; local Factory and Chrome
 * debugger ports are denied; raw devices are denied after the /dev allow so the deny wins.
 */
export class SeatbeltAgentPolicy implements SandboxPolicy {
  private readonly input: AgentPolicyInput;

  constructor(input: AgentPolicyInput) {
    this.input = input;
  }

  render(): string {
    const { home, writableRoots, readableRoots = [], deniedLocalPorts = DEFAULT_DENIED_LOCAL_PORTS } = this.input;
    return new SbplProfileBuilder(['Factory agent profile, generated by @factory/agent-user (adapted from SandVault).'])
      .byDefault('allow')
      .section(denyAllWrites())
      .section(denyOtherVolumes())
      .section(denyMounting())
      .section(denyHomes())
      .section(denyKeychains())
      .section(allowReads([home, ...writableRoots, ...readableRoots]))
      .section(allowWrites([home, ...writableRoots]))
      .section(denyRawDevices())
      .section(denyLocalPorts(deniedLocalPorts))
      .section(allowProcesses())
      .build();
  }
}
