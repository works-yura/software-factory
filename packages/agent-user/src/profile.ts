/**
 * The Seatbelt (sandbox-exec) profile agent commands run under: the second layer after the separate
 * user, which already keeps the agent out of everything file modes close. Adapted from SandVault's
 * profile (`sv`, "Configure sandbox-exec"):
 *
 * - kept: allow by default, then deny writes everywhere but a short list; deny reads of every home
 *   but the agent's own; deny the login keychains (System.keychain stays: CA roots); deny raw disks,
 *   packet capture and mounting (disk arbitration, network shares, Finder over Apple events);
 *   process info for `ps`.
 * - changed: SandVault denies all of /Volumes; Factory's card folders live on a data disk, so reads
 *   and writes there are allowed for the card folders only (and lookup of the folders above them).
 * - added: no connections to the local ports of the Factory server and the owner's Chrome debugger.
 *
 * Last match wins in SBPL, so every re-allow follows its deny.
 */

import { dirname } from 'node:path';

export interface AgentProfileInput {
  /** The agent user's home: readable and writable. */
  home: string;
  /** Card folders: readable and writable, wherever they are (also under /Volumes). */
  writableRoots: readonly string[];
  /** Extra read-only folders (shared tools). */
  readableRoots?: readonly string[];
  /** Local TCP ports the agent must not connect to: the Factory server, Chrome's debugger. */
  deniedLocalPorts?: readonly number[];
}

export const DEFAULT_DENIED_LOCAL_PORTS = [5874, 9222] as const;

/** A path as an SBPL string literal. */
export function sbplString(path: string): string {
  if (path.includes('\0') || path.includes('\n')) throw new Error(`Path ${JSON.stringify(path)} cannot go in a sandbox profile.`);
  return `"${path.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** Every folder above `path`, outermost first, without `/`. */
function ancestors(path: string): string[] {
  const result: string[] = [];
  for (let dir = dirname(path); dir !== '/' && dir !== '.'; dir = dirname(dir)) result.unshift(dir);
  return result;
}

const list = (items: readonly string[], indent = '    ') => items.map(item => `${indent}${item}`).join('\n');

export function agentProfile(input: AgentProfileInput): string {
  const writable = [...new Set(input.writableRoots)];
  const readable = [...new Set([...writable, ...(input.readableRoots ?? [])])];
  const ports = input.deniedLocalPorts ?? DEFAULT_DENIED_LOCAL_PORTS;
  for (const port of ports) {
    if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error(`Port ${port} is not a TCP port.`);
  }
  // Lookup of each folder above an allowed one: without it, path resolution into the allowed
  // subtree fails on the denied parents.
  const lookups = [...new Set([input.home, ...readable].flatMap(ancestors))];

  return `;; Factory agent profile (generated by @factory/agent-user; adapted from SandVault)
(version 1)
(allow default)

;; Writes: nowhere, except the lines that follow.
(deny file-write*
    (subpath "/"))

;; Reads of other disks: none, except the card folders below.
(deny file-read*
    (subpath "/Volumes"))
(allow file-read*
    (subpath "/Volumes/Macintosh HD"))

;; No mounting: disk arbitration, network shares, Finder over Apple events.
(deny file-mount file-unmount)
(deny mach-lookup
    (global-name "com.apple.DiskArbitration.diskarbitrationd")
    (global-name "com.apple.NetAuthAgent")
    (global-name "com.apple.NetAuthSysAgent")
    (global-name "com.apple.appleeventsd"))

;; Raw disks and packet capture, whatever /dev allows below.
(deny file-read* file-write*
    (regex #"^/dev/r?disk")
    (regex #"^/private/dev/r?disk")
    (regex #"^/dev/bpf"))

;; Homes: none but the agent's own.
(deny file-read*
    (subpath "/Users"))

;; Keychains: none but System.keychain (public CA roots).
(deny file-read*
    (subpath "/Library/Keychains"))
(allow file-read*
    (literal "/Library/Keychains/System.keychain"))

;; What the agent may read: its home, the card folders, and lookup of the folders above them.
(allow file-read*
    (literal "/Users")
${list(lookups.map(dir => `(literal ${sbplString(dir)})`))}
    (subpath ${sbplString(input.home)})
${list(readable.map(dir => `(subpath ${sbplString(dir)})`))})

;; What the agent may write: its home, the card folders, temp folders, devices (file modes guard them).
(allow file-write*
    (subpath ${sbplString(input.home)})
${list(writable.map(dir => `(subpath ${sbplString(dir)})`))}
    (subpath "/tmp")
    (subpath "/private/tmp")
    (subpath "/var/folders")
    (subpath "/private/var/folders")
    (subpath "/dev"))
${
  ports.length
    ? `
;; Local services that are not the agent's: the Factory server, the owner's Chrome debugger.
(deny network-outbound
${list(ports.map(port => `(remote ip "localhost:${port}")`))})
`
    : ''
}
;; Process info for ps; ps itself is setuid and must run unsandboxed.
(allow process-info*)
(allow sysctl-read)
(allow process*)
(allow process-exec
    (literal "/bin/ps")
    (with no-sandbox))
`;
}
